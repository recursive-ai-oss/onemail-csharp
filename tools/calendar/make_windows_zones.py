#!/usr/bin/env python3
"""Generate src/OneMail.Calendar/TimeZones/WindowsZones.cs from CLDR's windowsZones.xml (territory 001 rows).

  make_windows_zones.py <windowsZones.xml> <out.cs>

The XML is CLDR release-47 common/supplemental/windowsZones.xml (Unicode License V3; see THIRD-PARTY-NOTICES.md).
"""
import hashlib, sys, xml.etree.ElementTree as ET

src, out = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
root = ET.fromstring(data)
rows = []
rev = {}  # IANA name -> Windows name; the 001 row wins, then the first territory row in file order
rev001 = set()
for mz in root.iter('mapZone'):
    win, names, terr = mz.get('other'), mz.get('type').split(), mz.get('territory')
    if terr == '001':
        rows.append((win, names[0]))
    for n in names:
        if terr == '001' or n not in rev:
            if n in rev and n in rev001 and rev[n] != win:
                raise SystemExit('two 001 rows for ' + n)
            rev[n] = win
            if terr == '001':
                rev001.add(n)
rows.sort()
irows = sorted(rev.items())
with open(out, 'w', encoding='utf-8', newline='\n') as f:
    f.write('// <auto-generated>tools/calendar/make_windows_zones.py from CLDR release-47 windowsZones.xml (sha256 %s).</auto-generated>\n' % hashlib.sha256(data).hexdigest())
    f.write('// Unicode License V3, Copyright (c) 1991-2025 Unicode, Inc. See THIRD-PARTY-NOTICES.md.\n')
    f.write('namespace RecursiveAI.OneMail.Calendar.TimeZones;\n\n')
    f.write('internal static partial class WindowsZones\n{\n')
    f.write('    // Windows time zone name -> the IANA zone CLDR gives for the default territory (001).\n')
    f.write('    internal static readonly (string Windows, string Iana)[] Rows =\n    [\n')
    for w, i in rows:
        f.write('        ("%s", "%s"),\n' % (w, i))
    f.write('    ];\n\n')
    f.write('    // IANA zone name -> Windows time zone name, every name CLDR lists in any territory (001 row first). Used when the runtime only knows Windows ids.\n')
    f.write('    private static readonly (string Iana, string Windows)[] IanaRows =\n    [\n')
    for i, w in irows:
        f.write('        ("%s", "%s"),\n' % (i, w))
    f.write('    ];\n}\n')
print(len(rows), 'rows', len(irows), 'iana rows')
