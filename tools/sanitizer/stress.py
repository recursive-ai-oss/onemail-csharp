#!/usr/bin/env python3
"""Writes hostile-size inputs for the sanitiser into a directory: tools/sanitizer/stress.py OUTDIR. Each file is named for the shape it stresses."""
import os, sys
out = sys.argv[1]; os.makedirs(out, exist_ok=True)
def w(name, s): open(os.path.join(out, name + ".html"), "w", encoding="utf-8").write(s)
w("nest-div-100k", "<div>" * 100_000)
w("unclosed-b-1m", "<b>x" * 1_000_000)
w("nest-a-200k", "<a href=http://h.test/>x" * 200_000)
w("attrs-200k", "<p " + " ".join(f"a{i}=1" for i in range(200_000)) + ">x</p>")
w("attrs-dup-200k", "<p " + "class=a " * 200_000 + ">x</p>")
w("css-rules-300k", "<style>" + "a{color:red}" * 300_000 + "</style><a>x</a>")
w("css-not-10k", "<style>" + ":not(" * 10_000 + "a" + ")" * 10_000 + "{color:red}</style>")
w("css-calc-100k", "<p style=\"width:" + "calc(" * 100_000 + "1px" + ")" * 100_000 + "\">x</p>")
w("css-selector-long", "<style>" + ",".join(f"div.c{i} > p.d{i} + span" for i in range(100_000)) + "{color:red}</style>")
w("css-decls-300k", "<p style=\"" + "color:red;" * 300_000 + "\">x</p>")
w("css-media-nest", "<style>" + "@media screen{" * 50_000 + "a{color:red}" + "}" * 50_000 + "</style>")
w("css-url-4m", "<p style=\"background:url('http://h.test/" + "a" * 4_000_000 + "')\">x</p>")
w("css-escapes", "<style>" + "\\" * 2_000_000 + "</style>")
w("table-nest-50k", "<table><tr><td>" * 50_000)
w("misnest-1m", "<b><i>x</b></i>" * 500_000)
w("misnest-formatting-adopt", "<a><b><a></b></a>" * 100_000)
w("font-reconstruct", "<p><font>" * 100_000)
w("srcset-1m", "<img srcset=\"" + ",".join(f"http://h.test/{i} {i}w" for i in range(60_000)) + "\">")
w("pre-newline-100k", "<pre>\n</pre>" * 100_000)
w("pre-nest", "<pre>\n" * 5000)
w("class-1m-tokens", "<p class=\"" + " ".join(f"c{i}" for i in range(500_000)) + "\">x</p>")
w("br-1m", "<br>" * 1_000_000)
w("text-8m", "x" * 8_000_000)
w("style-elements-200k", "<style>a{}</style>" * 200_000)
w("img-unique-100k", "".join(f"<img src=\"http://h.test/{i}\">" for i in range(100_000)))
w("comments-1m", "<!--x-->" * 1_000_000)
w("entities-2m", "&amp;" * 2_000_000)
w("deep-inline-then-block", "<span>" * 5000 + "<div>" * 5000)
w("svg-nest", "<svg>" * 100_000)
w("noscript-style-mix", "<noscript><style>" * 50_000)
w("unclosed-tags-lt", "<" * 3_000_000)
w("attr-value-8m", "<p title=\"" + "a" * 7_900_000 + "\">x</p>")
