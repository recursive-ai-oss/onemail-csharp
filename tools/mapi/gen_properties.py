#!/usr/bin/env python3
"""Generate src/OneMail/Mapi/MapiPid.g.cs from tools/mapi/properties.tsv.

    python3 tools/mapi/gen_properties.py

The output is committed, so building needs no script; run this after editing the table.
"""
import pathlib
import sys

here = pathlib.Path(__file__).resolve().parent
root = here.parent.parent
rows = [l.rstrip("\n").split("\t") for l in (here / "properties.tsv").read_text().splitlines() if l and not l.startswith("#")]

tags, aliases, named = [], [], []
for r in rows:
    if r[0] == "tag":
        tags.append((int(r[1], 16), r[2]))
    elif r[0] == "alias":
        aliases.append((int(r[1], 16), r[2]))
    elif r[0] == "named":
        named.append((r[1], int(r[2], 16), r[3]))
    else:
        sys.exit(f"bad row {r}")

ids = [i for i, _ in tags]
assert len(ids) == len(set(ids)), "duplicate tag id"
const_names = [n for _, n in tags] + [n for _, n in aliases]
assert len(const_names) == len(set(const_names)), "duplicate name"
assert len({(s, l) for s, l, _ in named}) == len(named), "duplicate named property"
assert len({n for _, _, n in named}) == len(named), "duplicate named property name"

out = []
w = out.append
w("// <auto-generated>Generated by tools/mapi/gen_properties.py from tools/mapi/properties.tsv. Do not edit.</auto-generated>")
w("")
w("namespace RecursiveAI.OneMail.Mapi;")
w("")
w("/// <summary>Property IDs of the tagged properties the readers use, named as in MS-OXPROPS without the <c>PidTag</c> prefix.</summary>")
w("public static class MapiPid")
w("{")
for i, n in sorted(tags + aliases):
    w(f"    /// <summary>{n} (0x{i:04X}).</summary>")
    w(f"    public const ushort {n.removeprefix('PidTag')} = 0x{i:04X};")
    w("")
out.pop()
w("}")
w("")
w("/// <summary>Names of the named properties the readers use, as in MS-OXPROPS.</summary>")
w("public static class MapiNames")
w("{")
for s, l, n in named:
    w(f"    /// <summary>{n}: property set {s}, LID 0x{l:04X}.</summary>")
    w(f"    public static readonly MapiNamedProperty {n.removeprefix('PidLid')} = new(MapiPropertySets.{s}, 0x{l:04X}u);")
    w("")
out.pop()
w("}")
w("")
w("public static partial class MapiPropertyNames")
w("{")
w("    private static readonly ushort[] s_ids =")
w("    [")
for i, _ in sorted(tags):
    w(f"        0x{i:04X},")
w("    ];")
w("")
w("    private static readonly string[] s_names =")
w("    [")
for _, n in sorted(tags):
    w(f'        "{n}",')
w("    ];")
w("")
w("    private static readonly (MapiNamedProperty Property, string Name)[] s_named =")
w("    [")
for s, l, n in named:
    w(f'        (MapiNames.{n.removeprefix("PidLid")}, "{n}"),')
w("    ];")
w("}")
w("")
(root / "src/OneMail/Mapi/MapiPid.g.cs").write_text("\n".join(out))
print(f"{len(tags)} tagged, {len(aliases)} aliases, {len(named)} named")
